#!/usr/bin/env python3
"""Generate the homepage's three newest changelog entries from ngrok's RSS feed."""

import html
from html.parser import HTMLParser
from pathlib import Path
import sys
from datetime import timezone
from email.utils import parsedate_to_datetime
from urllib.parse import urlparse
from urllib.request import Request, urlopen
import xml.etree.ElementTree as ET

FEED_URL = "https://ngrok.com/changelog/rss.xml"
OUTPUT = Path(__file__).resolve().parents[2] / "snippets/homepage-changelog.mdx"
MAX_BYTES = 2 * 1024 * 1024


class PlainText(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.parts = []

    def handle_data(self, data):
        self.parts.append(data)

    def handle_starttag(self, tag, attrs):
        self.parts.append(" ")

    def handle_endtag(self, tag):
        self.parts.append(" ")


def text(value):
    parser = PlainText()
    parser.feed(value)
    return " ".join("".join(parser.parts).split())


def escape(value):
    # RSS content is text, never executable MDX/JSX or Markdown.
    return (html.escape(value, quote=True).replace("{", "&#123;")
            .replace("}", "&#125;").replace("`", "&#96;"))


def render(feed):
    if b"<!DOCTYPE" in feed.upper() or b"<!ENTITY" in feed.upper():
        raise ValueError("RSS document declarations are not supported")
    root = ET.fromstring(feed)
    if root.tag != "rss" or root.find("channel") is None:
        raise ValueError("Expected an RSS feed with a channel")
    entries = []
    for item in root.findall("./channel/item"):
        title = text(item.findtext("title", ""))
        link = item.findtext("link", "").strip()
        url = urlparse(link)
        if not title or url.scheme != "https" or url.netloc != "ngrok.com" or not url.path.startswith("/changelog/"):
            raise ValueError("Invalid changelog title or URL")
        date = parsedate_to_datetime(item.findtext("pubDate", ""))
        if date.tzinfo is None:
            raise ValueError("RSS dates must include a timezone")
        entries.append((date.astimezone(timezone.utc), link, title, text(item.findtext("description", ""))))
    entries.sort(key=lambda entry: (entry[0], entry[1]), reverse=True)
    unique = {entry[1]: entry for entry in reversed(entries)}
    latest = sorted(unique.values(), key=lambda entry: (entry[0], entry[1]), reverse=True)[:3]
    if len(latest) < 3:
        raise ValueError("Expected at least three distinct changelog entries")
    lines = ['{/* Generated by custom/scripts/fetch-homepage-changelog.py. Do not edit. */}', '',
             '<div className="docs-home-updates not-prose">']
    for date, link, title, description in latest:
        label = f"{date.strftime('%B')} {date.day}, {date.year}"
        lines.extend([f'  <a href="{escape(link)}">',
                      f'    <span className="docs-home-date">{label}</span>',
                      f'    <span className="docs-home-title">{escape(title)}</span>'])
        if description:
            lines.append(f'    <p>{escape(description)}</p>')
        lines.append('  </a>')
    lines.append('</div>')
    return '\n'.join(lines) + '\n'


def main():
    request = Request(FEED_URL, headers={"User-Agent": "ngrok-docs-changelog-sync/1.0"})
    with urlopen(request, timeout=30) as response:
        feed = response.read(MAX_BYTES + 1)
    if len(feed) > MAX_BYTES:
        raise ValueError("RSS feed exceeds 2 MiB")
    result = render(feed)
    if OUTPUT.exists() and OUTPUT.read_text() == result:
        print("Homepage changelog is current.")
        return
    # Only replace the previous snapshot after fetch, parse, and validation succeed.
    temporary = OUTPUT.with_suffix('.mdx.tmp')
    temporary.write_text(result)
    temporary.replace(OUTPUT)
    print("Updated homepage changelog.")


if __name__ == '__main__':
    try:
        main()
    except Exception as error:
        print(f"Changelog refresh failed; existing snippet preserved: {error}", file=sys.stderr)
        sys.exit(1)
